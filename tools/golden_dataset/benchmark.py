"""Retrieval benchmark export: queries and the source locations that answer them, nothing else."""

import hashlib
import json
from collections import Counter
from pathlib import Path

from .reporting import accepted, report
from .snapshot import verify_snapshot
from .storage import now
from .validation import validate

FORMAT = 'golden-retrieval-benchmark'
FORMAT_VERSION = '1.0'
DESCRIPTION = {
    'queries.jsonl': 'One query per line. relevant is a list of groups: every group must be retrieved, '
                     'and any one location in a group satisfies it. sections and documents are coarser '
                     'targets derived from the same evidence. group_id links a question to its paraphrase.',
    'locations': 'path is relative to the documentation repository root. start/end are end-exclusive '
                 'Unicode code point offsets, and line_start/line_end 1-based lines, into the file decoded '
                 'as UTF-8 without BOM and with line endings normalized to LF. text is that exact range, '
                 'including markup. exact=false marks a location mapped at section or file level.',
    'source_files': 'Every file an exported query points into (locations and sections), each with the SHA-256 '
                    'of its normalized form, so CRLF and LF checkouts agree.',
}
LIMITATIONS = [
    'Each question lists only the locations it was written from; other passages that answer it '
    'equally well are not listed.',
    'Questions were generated by a language model while reading each page and reviewed by another model; '
    'a sample is human-audited before an audited_ready release.',
]


def normalized(path):
    return path.read_text(encoding='utf-8-sig')


def benchmark(state, destination, ready_only=False, approved_only=False):
    verify_snapshot(state)
    metrics = report(state)
    if ready_only and not metrics['ready']:
        raise ValueError('Dataset is not ready: resolve coverage, validation, and audit gates first.')
    target = Path(destination)
    target.mkdir(parents=True, exist_ok=True)
    if any(target.iterdir()):
        raise ValueError('Export directory must be empty; use a new version directory.')
    repo, files = Path(state['repo']), {}

    def source(path):
        if path not in files:
            files[path] = normalized(repo / path)
        return files[path]

    def location(path, start, end, exact):
        text = source(path)
        return {'path': path, 'start': start, 'end': end, 'line_start': text.count('\n', 0, start) + 1,
                'line_end': text.count('\n', 0, max(start, end - 1)) + 1, 'text': text[start:end], 'exact': exact}

    queries = []
    selected = [c for c in accepted(state) if not approved_only or c['human_status'] == 'approved']
    if approved_only and not selected:
        raise ValueError('No human-approved questions to export; approve questions in review first.')
    for c in selected:
        if validate(c, state, check_duplicates=False):
            continue
        relevant, sections = [], []
        for group in c['evidence_groups']:
            any_of = []
            for alternative in group['alternatives']:
                # One quote can map to adjacent source blocks; consumers get one range per file.
                by_file = {}
                for span in alternative['source_spans']:
                    by_file.setdefault(span['source_path'], []).append(span)
                for path, spans in by_file.items():
                    item = location(path, min(s['start'] for s in spans), max(s['end'] for s in spans),
                                    all(s['precision'] == 'exact_block' for s in spans))
                    if item not in any_of:
                        any_of.append(item)
                section = state['sections'][alternative['section_id']]['source']
                entry = {'path': section['source_path'], 'heading_path': section['heading_path'],
                         'start': section['start'], 'end': section['end']}
                if entry not in sections:
                    sections.append(entry)
            relevant.append({'any_of': any_of})
        group_id = 'q-' + c['id'][:16]
        record = {'relevant': relevant, 'sections': sections,
                  'documents': sorted({item['path'] for group in relevant for item in group['any_of']}),
                  'tags': {key: c[key] for key in ('question_type', 'difficulty', 'persona', 'product')}}
        queries.append({'id': group_id, 'group_id': group_id, 'variant': 'original', 'query': c['question'], **record})
        if c.get('paraphrase') and c.get('paraphrase_status') == 'accepted':
            queries.append({'id': group_id + '-p', 'group_id': group_id, 'variant': 'paraphrase', 'query': c['paraphrase'], **record})

    body = ''.join(json.dumps(q, ensure_ascii=False) + '\n' for q in queries)
    # Only the files the exported questions point into, so ingestion can pick them up directly.
    corpus = {item['path'] for q in queries for group in q['relevant'] for item in group['any_of']}
    corpus |= {section['path'] for q in queries for section in q['sections']}
    hashes = {path: hashlib.sha256(normalized(repo / path).encode('utf-8')).hexdigest() for path in sorted(corpus)}
    (target / 'queries.jsonl').write_text(body, encoding='utf-8', newline='\n')
    manifest = {'format': FORMAT, 'format_version': FORMAT_VERSION,
                'dataset_id': hashlib.sha256(body.encode('utf-8')).hexdigest()[:16], 'created_at': now(),
                'release_status': 'audited_ready' if metrics['ready'] else 'candidate_incomplete',
                # human_approved: every question was approved in review; model_accepted: also unreviewed ones.
                'selection': 'human_approved' if approved_only else 'model_accepted',
                'docs': {'commit': state['snapshot']['commit'], 'snapshot_id': state['snapshot_id'], 'source_files': hashes},
                'counts': {'queries': len(queries), 'questions': sum(q['variant'] == 'original' for q in queries),
                           'by_variant': dict(Counter(q['variant'] for q in queries)),
                           'by_question_type': dict(Counter(q['tags']['question_type'] for q in queries if q['variant'] == 'original')),
                           'by_product': dict(Counter(q['tags']['product'] for q in queries if q['variant'] == 'original'))},
                'description': DESCRIPTION, 'limitations': LIMITATIONS}
    (target / 'manifest.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n', encoding='utf-8', newline='\n')
    return manifest['counts']
